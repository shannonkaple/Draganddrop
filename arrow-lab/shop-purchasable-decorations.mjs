// A GitHub Pages 200 can be an HTML fallback, not a published transparent PNG.
// HEAD avoids downloading dozens of large images on every student launch.
export function isPublishedPngResponse(response){
 if(!response?.ok)return false;
 const type=response.headers?.get?.('content-type');
 return typeof type==='string' && /^image\/png(?:\s*;|\s*$)/i.test(type.trim());
}

// Fail closed: an unpublished or unavailable PNG cannot be bought as a broken image.
// probe receives the unmodified repository-relative artPath and returns a boolean.
export async function publishedShopDecorations(probe){
 if(typeof probe!=='function')throw new TypeError('An image-availability check is required');
 const checked=await Promise.all(newShopDecorationCatalog.map(async item=>{
   try{return (await probe(item.artPath))?item:null}catch{return null}
 }));
 return checked.filter(Boolean);
}

// Retain the metadata for already-owned items when a network probe fails.
// This NEVER makes an unpublished decoration available to buy.
export function catalogWithArtAvailability(catalog,published){
 const readyIds=new Set(published.map(item=>item.id));
 return catalog.map(item=>({...item,artUnavailable:!readyIds.has(item.id)}));
}
